/** 精确匹配；province 用于同名城市消歧（如 吉林市/吉林、朝阳）。 */
export function findCityCoords(cityName: string, province?: string): CityCoord | null {
  const name = cityName.trim()
  if (!name) return null
  const matches = CITY_COORDS.filter((c) => c.cityName === name)
  if (matches.length === 0) return null
  if (province) {
    const byProvince = matches.find((c) => c.province === province)
    if (byProvince) return byProvince
  }
  return matches[0]
}

/** 包含匹配（城市名或省份），预留搜索建议。 */
export function searchCityCoords(keyword: string, limit = 10): CityCoord[] {
  const kw = keyword.trim()
  if (!kw) return []
  return CITY_COORDS.filter((c) => c.cityName.includes(kw) || c.province.includes(kw)).slice(0, limit)
}
